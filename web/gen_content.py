#!/usr/bin/env python3
"""Convert the course README.md into static/lessons.js for the web UI.

Parses lessons (## Lesson N — Title) and extracts executable PromQL queries
from ```promql / ```prometheus fences, taking the last non-comment line of
each block as the runnable query.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent
readme = (ROOT.parent / "README.md").read_text()

# Split into intro + lessons.
parts = re.split(r"^## ", readme, flags=re.M)
intro = parts[0].strip()
lessons = []
for chunk in parts[1:]:
    title, _, body = chunk.partition("\n")
    title = title.strip()
    if not title.lower().startswith("lesson"):
        continue
    m = re.match(r"Lesson\s+(\d+)\s+[—-]\s+(.*)", title)
    num = int(m.group(1)) if m else len(lessons) + 1
    name = m.group(2).strip() if m else title
    # Pull runnable queries from promql/prometheus code fences.
    queries = []
    for fence in re.findall(r"```(?:promql|prometheus)\n(.*?)```", body, flags=re.S):
        lines = [l for l in fence.splitlines()
                 if l.strip() and not l.strip().startswith("#")]
        if lines:
            queries.append(lines[-1].strip())
    lessons.append({"n": num, "title": name, "body": body.strip(), "queries": queries})

data = {"intro": intro, "lessons": lessons}
out = ROOT / "static" / "lessons.js"
out.write_text("// GENERATED by gen_content.py — do not edit by hand.\n"
               "window.COURSE = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n")
print(f"wrote {out} with {len(lessons)} lessons, "
      f"{sum(len(l['queries']) for l in lessons)} queries")
